"""Signal House lessons, with examples computed by Python references."""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Callable


def _lesson(
    lesson_id: str,
    chapter: str,
    title: str,
    *,
    concept: str,
    story: str,
    goal: str,
    starter: str,
    solution: str,
    inputs: list[list],
    reference: Callable[..., list],
    hints: list[str],
    discovery: str,
    review: str,
    prediction: str,
    macros: list[str] | None = None,
) -> dict:
    examples = [{"input": args, "output": reference(*args)} for args in inputs]
    return {
        "id": lesson_id,
        "chapter": chapter,
        "title": title,
        "concept": concept,
        "story": story,
        "goal": goal,
        "starter": starter,
        "solution": solution,
        "examples": examples[:3],
        "heldout": examples[3:],
        "hints": hints,
        "discovery": discovery,
        "review": review,
        "prediction": prediction,
        "macros": macros or [],
    }


