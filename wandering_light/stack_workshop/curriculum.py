"""The Signal House bench book. Each reference takes and returns a whole stack."""


def _lesson(
    lesson_id,
    *,
    chapter,
    title,
    concept,
    story,
    goal,
    starter,
    solution,
    inputs,
    reference,
    hints,
    discovery,
    review,
    prediction,
    macros=(),
):
    cases = [{"input": stack, "output": reference(*stack)} for stack in inputs]
    return {
        "id": lesson_id,
        "chapter": chapter,
        "title": title,
        "concept": concept,
        "story": story,
        "goal": goal,
        "starter": starter,
        "solution": solution,
        "examples": cases[:3],
        "heldout": cases[3:],
        "hints": hints,
        "discovery": discovery,
        "review": review,
        "prediction": prediction,
        "macros": list(macros),
    }


