"""Re-certify the loop-bearing ``stack_pbe_v2`` labels under Levin Kt.

The committed artifact was generated by breadth-first search, so its witnesses
minimise op count. This experiment checks the 101 stored programs containing
``map``, ``fold`` or ``filter`` against the cost-ordered product-behaviour
search:

    uv run python -m experiments.recertify_stack_machine_cost

It emits a compact JSON result on stdout and progress on stderr. Fuel is the
sum of the work needed to run the program on every example in a PBE task; the
program itself is encoded once. Paths are compared exactly through
``2**Kt = fuel * 2**len(program)``.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import sys
import time
from collections import defaultdict
from pathlib import Path

from wandering_light.stack_machine import parse_stack
from wandering_light.stack_machine_corpus import (
    CostedPath,
    behaviour_key,
    expand_cost,
    replay_costed,
)

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CORPUS = ROOT / "wandering_light/evals/data/stack_pbe_v2.jsonl.gz"
LOOP_OPS = frozenset({"map", "fold", "filter"})
LOOP_FAMILIES = frozenset({"with_map", "with_fold", "with_filter"})
EXPECTED_LOOP_TASKS = 101


def read_corpus(path: Path) -> list[dict]:
    with gzip.open(path, "rt") as handle:
        return [json.loads(line) for line in handle]


def has_loop_witness(task: dict) -> bool:
    return not LOOP_OPS.isdisjoint(task["program"])


def maximum_relevant_depth(examples: int, score_limit: int) -> int:
    """Largest depth whose theoretical minimum Kt reaches ``score_limit``."""
    if examples < 1:
        raise ValueError("examples must be positive")
    if score_limit < 0:
        raise ValueError("score_limit must be non-negative")
    depth = 0
    while True:
        candidate = depth + 1
        minimum_score = (examples * candidate) << candidate
        if minimum_score > score_limit:
            return depth
        depth = candidate


def encode_path(path: CostedPath) -> dict:
    return {
        "program": list(path.program),
        "length": path.length,
        "example_fuels": list(path.example_fuels),
        "fuel": path.fuel,
        "score": path.score,
        "kt_bits": path.kt,
    }


def recertify(rows: list[dict], max_states: int | None) -> dict:
    selected = [task for task in rows if has_loop_witness(task)]
    if len(selected) != EXPECTED_LOOP_TASKS:
        raise ValueError(
            f"expected {EXPECTED_LOOP_TASKS} loop witnesses, found {len(selected)}"
        )

    roots: dict[tuple[str, ...], list[dict]] = defaultdict(list)
    for task in selected:
        roots[tuple(task["inputs"])].append(task)

    outcomes = []
    search_stats = []
    for index, (encoded_inputs, tasks) in enumerate(roots.items(), start=1):
        started = time.monotonic()
        inputs = tuple(parse_stack(text) for text in encoded_inputs)
        incumbents = {}
        for task in tasks:
            produced, path = replay_costed(inputs, tuple(task["program"]))
            target = behaviour_key(tuple(parse_stack(text) for text in task["outputs"]))
            if behaviour_key(produced) != target:
                raise ValueError(f"stored witness does not reproduce task: {task}")
            incumbents[id(task)] = path

        score_limit = max(path.score for path in incumbents.values())
        max_depth = maximum_relevant_depth(len(inputs), score_limit)
        found, complete = expand_cost(
            inputs,
            max_depth=max_depth,
            max_states=max_states,
            max_score=score_limit,
        )
        if not complete:
            raise RuntimeError(
                f"root {encoded_inputs!r} hit max_states={max_states}; "
                "raise the limit before treating the result as a certificate"
            )

        seconds = time.monotonic() - started
        search_stats.append(
            {
                "inputs": list(encoded_inputs),
                "tasks": len(tasks),
                "max_depth": max_depth,
                "max_score": score_limit,
                "behaviours": len(found),
                "seconds": seconds,
            }
        )
        print(
            f"[{index}/{len(roots)}] {len(tasks):>2} tasks, depth {max_depth}, "
            f"{len(found):>9,} behaviours, {seconds:>6.1f}s",
            file=sys.stderr,
            flush=True,
        )

        for task in tasks:
            target = behaviour_key(tuple(parse_stack(text) for text in task["outputs"]))
            candidate = found.get(target)
            if candidate is None:
                raise RuntimeError(f"cost search lost the stored target: {task}")
            incumbent = incumbents[id(task)]
            if candidate.score > incumbent.score:
                raise AssertionError("stored path was inside the search bound")
            outcomes.append(
                {
                    "family": task["family"],
                    "split": task["split"],
                    "inputs": task["inputs"],
                    "outputs": task["outputs"],
                    "changed": candidate.score < incumbent.score,
                    "discrepancy_bits": incumbent.kt - candidate.kt,
                    "old": encode_path(incumbent),
                    "new": encode_path(candidate),
                }
            )

    changed = [outcome for outcome in outcomes if outcome["changed"]]
    changed.sort(key=lambda outcome: outcome["discrepancy_bits"], reverse=True)
    by_family = {}
    for family in sorted({task["family"] for task in selected}):
        family_outcomes = [row for row in outcomes if row["family"] == family]
        by_family[family] = {
            "tasks": len(family_outcomes),
            "changed": sum(row["changed"] for row in family_outcomes),
        }

    named_family_rows = [task for task in rows if task["family"] in LOOP_FAMILIES]
    return {
        "corpus_tasks": len(rows),
        "loop_tasks": len(selected),
        "loop_tasks_in_named_families": sum(
            task["family"] in LOOP_FAMILIES for task in selected
        ),
        "all_tasks_in_named_families": len(named_family_rows),
        "roots": len(roots),
        "fuel_aggregation": "sum across PBE examples",
        "path_weight": "Kt = len(program) + log2(fuel)",
        "changed": len(changed),
        "unchanged": len(outcomes) - len(changed),
        "largest_discrepancy_bits": (
            changed[0]["discrepancy_bits"] if changed else 0.0
        ),
        "witnesses_with_unequal_example_fuel": sum(
            len(set(outcome["old"]["example_fuels"])) > 1 for outcome in outcomes
        ),
        "by_family": by_family,
        "search": search_stats,
        "changed_labels": changed,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("corpus", type=Path, nargs="?", default=DEFAULT_CORPUS)
    parser.add_argument("--max-states", type=int, default=2_000_000)
    args = parser.parse_args(argv)

    result = recertify(read_corpus(args.corpus), args.max_states)
    result["corpus_sha256"] = hashlib.sha256(args.corpus.read_bytes()).hexdigest()
    json.dump(result, sys.stdout, indent=2, sort_keys=True)
    sys.stdout.write("\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
