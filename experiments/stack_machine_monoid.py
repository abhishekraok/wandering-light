"""How much does composition actually generate? The semantic monoid, by BFS.

Reachability from one root answers "what states exist", which on this basis is
dominated by inert literal stacking and scores a contracting op like `eq?` at
zero. The question #42 actually asks is different: composed with each other,
how many *distinct behaviours* does a basis generate?

Measure it directly. Fix a probe set of inputs. A program's behaviour is the
tuple of results it produces on every probe, with `None` where its guard
refuses. Two programs are the same element of the monoid when their behaviour
tuples agree. BFS over behaviours, appending one op at a time, enumerates the
monoid generated by the basis -- and its growth curve is the expressiveness
number, comparable across bases of different sizes.

    uv run python experiments/stack_machine_monoid.py > monoid.json
"""

import json
import sys
import time
from collections.abc import Callable, Sequence

from wandering_light.stack_machine import OPS, Config, parse_program, run

Behaviour = tuple


def behaviour_bfs(
    names: Sequence[str],
    step: Callable[[str, object], object],
    probes: Sequence[object],
    max_depth: int,
    deadline: float,
    max_nodes: int = 4_000_000,
) -> dict:
    """BFS over distinct behaviours. `step(name, value)` returns None if refused."""
    identity: Behaviour = tuple(probes)
    seen = {identity}
    frontier = [identity]
    levels = []
    dead = tuple([None] * len(probes))

    for depth in range(1, max_depth + 1):
        started = time.time()
        nxt = []
        for behaviour in frontier:
            for name in names:
                out = tuple(
                    None if value is None else step(name, value) for value in behaviour
                )
                if out == dead:
                    continue  # the absorbing element: refused on every probe
                if out not in seen:
                    seen.add(out)
                    nxt.append(out)
        levels.append(
            {
                "depth": depth,
                "new": len(nxt),
                "cumulative": len(seen),
                "growth": len(seen) / max(1, len(seen) - len(nxt)),
                "seconds": round(time.time() - started, 2),
            }
        )
        frontier = nxt
        if not frontier or time.time() > deadline or len(seen) > max_nodes:
            break

    return {
        "levels": levels,
        "saturated": not frontier,
        "generators": len(names),
        "probes": len(probes),
    }


# --------------------------------------------------------------------------
# The stack machine
# --------------------------------------------------------------------------

STACK_PROBES = [
    "nil 1 cons 0 cons 1 cons",
    "1 0",
    "0 1",
    "nil",
    "nil 1 cons 1",
    "1 1 add 1",
    "nil 0 cons nil 1 cons",
    "true 1",
]

OP_BY_NAME = {op.name: op for op in OPS}


def stack_step(name, stack):
    op = OP_BY_NAME[name]
    config = Config(stack)
    if op.guard(config) is not None:
        return None
    new, _ = op.apply(config)
    return new


def stack_probe_values():
    values = []
    for source in STACK_PROBES:
        config = Config()
        for reached in run(parse_program(source), config):
            config = reached
        values.append(config.stack)
    return values


def stack_monoid(max_depth: int, deadline: float, ops=None) -> dict:
    names = [op.name for op in (ops or OPS)]
    return behaviour_bfs(names, stack_step, stack_probe_values(), max_depth, deadline)


# --------------------------------------------------------------------------
# wl-core-v1, the basis this one is meant to replace
# --------------------------------------------------------------------------


def old_basis_monoid(max_depth: int, deadline: float) -> dict:
    from wandering_light.basis_set import load_basis_set
    from wandering_light.executor import Executor
    from wandering_light.typed_list import TypedList

    functions = load_basis_set("wl-core-v1").to_function_def_set()
    executor = Executor(functions, enforce_membership=False)
    by_name = {f.name: f for f in functions}

    probes = [
        TypedList([1, 2, 3]),
        TypedList([1, 0, 1]),
        TypedList(["ab", "c"]),
        TypedList([True, False]),
        TypedList([1.5, 2.5]),
        TypedList([[1, 2], [3]], list),
        TypedList([0]),
        TypedList(["Hello"]),
    ]

    class Keyed:
        """Wrap a TypedList so behaviour tuples can go in a set.

        `__eq__` is the structural comparison and does the real work; the hash
        only has to agree with it, and is never persisted.
        """

        __slots__ = ("k", "tl")

        def __init__(self, tl):
            self.tl = tl
            self.k = tl.canonical_key()

        def __eq__(self, other):
            return isinstance(other, Keyed) and self.k == other.k

        def __hash__(self):
            return hash(repr(self.k))

    def wrapped_step(name, holder):
        try:
            result = executor.execute(by_name[name], holder.tl)
        except Exception:
            return None
        return None if result is None else Keyed(result)

    return behaviour_bfs(
        list(by_name),
        wrapped_step,
        [Keyed(p) for p in probes],
        max_depth,
        deadline,
    )


def main() -> None:
    budget = float(sys.argv[1]) if len(sys.argv) > 1 else 240.0
    started = time.time()
    out = {}

    out["stack_machine"] = stack_monoid(9, started + budget * 0.45)
    print(f"[{time.time() - started:6.1f}s] stack machine monoid done", file=sys.stderr)

    out["ablation"] = []
    depth = min(5, len(out["stack_machine"]["levels"]))
    full = stack_monoid(depth, started + budget * 2)["levels"][-1]["cumulative"]
    for op in OPS:
        kept = [o for o in OPS if o is not op]
        without = stack_monoid(depth, started + budget * 2, ops=kept)["levels"][-1][
            "cumulative"
        ]
        out["ablation"].append(
            {
                "op": op.name,
                "group": op.group,
                "without": without,
                "fraction_lost": 1 - without / full,
            }
        )
    out["ablation"].sort(key=lambda r: -r["fraction_lost"])
    out["ablation_full"] = full
    out["ablation_depth"] = depth
    print(f"[{time.time() - started:6.1f}s] ablation done", file=sys.stderr)

    try:
        out["old_basis"] = old_basis_monoid(6, time.time() + budget * 0.35)
    except Exception as error:
        out["old_basis"] = {"error": f"{type(error).__name__}: {error}"}
    print(f"[{time.time() - started:6.1f}s] old basis monoid done", file=sys.stderr)

    json.dump(out, sys.stdout)


if __name__ == "__main__":
    main()
